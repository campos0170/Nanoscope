"""The documentation is a SURFACE, and these are the claims on it that had gone wrong.

None of `docs/manual-markdown/manual.md`, `docs/inventory.json`, `docs/ARCHITECTURE.md` or
`docs/USER_GUIDE.md` is generated by introspecting the app, so nothing in them fixes itself.
Two of the claims they carried were not merely stale but ACTIVELY HARMFUL when followed:

* The merge walkthrough told the reader the `Merge sub-events` window was in MICROSECONDS and
  to type ``15000`` for 15 ms. The spinbox reads milliseconds with a maximum of 100, so Qt
  silently clamped that to 100 ms -- a ~6.7x over-merge, delivered with no warning, in the one
  step of the manual whose whole subject is that a wrong window fuses distinct translocations.
  (Its ancestor did the same in the other direction: a `15` typed into the old microsecond
  field was a 1000x UNDER-merge, which is what put the millisecond spinbox there.)
* The control reference gave the window's range as "0-100 ms". 0 is deliberately unreachable
  (:data:`~nanoscope.gui.merge_panel.MIN_WINDOW_MS`) precisely because it read as an "off"
  sentinel it never was -- at 0.0 the window is 0 samples and exactly-touching rows still
  merged.

and one whole behaviour was undocumented: the occupancy floor, which REFUSES a merge whose
span would be mostly open pore. A user following a documented tutorial step can hit a refusal;
if the documentation has never mentioned it, the refusal reads as the merge being broken --
which is exactly the report that produced this work.

Written the way ``tests/io/test_s3_io_guide.py`` is: read the app's own numbers first, then
check the documents against THEM, rather than grepping prose for its own sake. A doc test that
hard-codes the value it is checking rots in step with the doc.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from nanoscope.analysis.merge import MARGINAL_MERGE_OCCUPANCY, MIN_MERGE_OCCUPANCY
from nanoscope.core.project import VERSION as PROJECT_VERSION
from nanoscope.gui.merge_panel import DEFAULT_WINDOW_MS, MIN_WINDOW_MS

_DOCS = Path(__file__).resolve().parents[1] / "docs"
_MANUAL = _DOCS / "manual-markdown" / "manual.md"
_INVENTORY = _DOCS / "inventory.json"
_ARCH = _DOCS / "ARCHITECTURE.md"
_GUIDE = _DOCS / "USER_GUIDE.md"


@pytest.fixture(scope="module")
def manual() -> str:
    return _MANUAL.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def inventory() -> list[dict]:
    return json.loads(_INVENTORY.read_text(encoding="utf-8"))


def _control(inventory: list[dict], label: str, group: str) -> dict:
    hits = [c for area in inventory for c in area["controls"]
            if c["label"] == label and c.get("group") == group]
    assert len(hits) == 1, f"expected exactly one {label!r} in {group!r}, got {len(hits)}"
    return hits[0]


# ---------------------------------------------------------------------------------------------
# 1. THE DANGEROUS ONE: the walkthrough's merge step
# ---------------------------------------------------------------------------------------------
def test_merge_walkthrough_is_in_milliseconds_not_microseconds(manual, qapp):
    """The walkthrough must tell the reader the unit the spinbox actually speaks.

    The spinbox is consulted rather than trusted: ``15000`` typed into a control whose
    maximum is 100 is not an error the user is shown, it is a clamp.
    """
    from nanoscope.gui.merge_panel import MergePanel

    panel = MergePanel()
    try:
        assert panel.window_ms.suffix().strip() == "ms"
        maximum = panel.window_ms.maximum()
        panel.window_ms.setValue(15000.0)
        clamped = panel.window_ms.value()
    finally:
        panel.deleteLater()
    assert clamped == maximum, "the premise of this test: 15000 is silently clamped"

    step = manual.split("### Doing it after detection", 1)[1].split("### ", 1)[0]
    assert "**It is in milliseconds**" in step
    assert "15000" not in step and "µs" not in step
    assert "is `15`" in step
    assert f"{MIN_WINDOW_MS:g}–{maximum:g} ms" in step         # "0.01–100 ms"
    assert f"starts at {DEFAULT_WINDOW_MS:g} ms" in step


# ---------------------------------------------------------------------------------------------
# 2. The control reference's range, and that 0 is not an off switch
# ---------------------------------------------------------------------------------------------
def test_inventory_merge_window_range_has_a_real_minimum(inventory, qapp):
    from nanoscope.gui.merge_panel import MergePanel

    panel = MergePanel()
    try:
        lo, hi = panel.window_ms.minimum(), panel.window_ms.maximum()
    finally:
        panel.deleteLater()
    assert lo == MIN_WINDOW_MS

    notes = _control(inventory, "Window", "Merge sub-events")["notes"]
    assert f"Range {lo:g}–{hi:g} ms" in notes
    assert "Range 0–100 ms" not in notes and "Range 0-100 ms" not in notes
    # ...and the reason, because a minimum with no reason reads as an arbitrary limit.
    assert "There is NO 0" in notes


def test_manual_never_claims_the_merge_window_can_be_zero(manual):
    for stale in ("Range 0–100 ms", "Range 0-100 ms", "The field accepts 0–100,000 µs"):
        assert stale not in manual, stale


# ---------------------------------------------------------------------------------------------
# 3. The occupancy floor -- documented at all, and with the app's own numbers
# ---------------------------------------------------------------------------------------------
def _pct(fraction: float) -> str:
    return f"{fraction * 100:g}%"


def test_manual_documents_the_low_occupancy_refusal(manual):
    section = manual.split("### When the merge refuses", 1)
    assert len(section) == 2, "the merge walkthrough must explain the refusal"
    body = section[1].split("### ", 1)[0]
    assert _pct(MIN_MERGE_OCCUPANCY) in body            # the floor itself, 50%
    assert _pct(MARGINAL_MERGE_OCCUPANCY) in body       # the kept-but-recorded band, 80%
    # The status-bar sentence the user will actually see, so a refusal is recognisable.
    assert "mostly open pore" in body
    assert "Try a smaller window." in body
    # And the distinction that made the merge look broken: refused is not "nothing to merge".
    assert "to merge." in body and "declined" in body


def test_merge_all_reference_row_mentions_the_refusal(inventory):
    """The row used to list only the no-op message, which is the WRONG one of the two."""
    notes = _control(inventory, "Merge all", "Merge sub-events")["notes"]
    assert "No sub-events within" in notes          # the no-op, still true
    assert "REFUSED" in notes                       # ...and the refusal, which was missing
    assert "Nothing merged:" in notes
    assert _pct(MIN_MERGE_OCCUPANCY) in notes


def test_every_merge_entry_point_says_a_merge_can_be_refused(inventory, manual):
    """`Merge all`, a region merge and `Merge with next` share one floor, so they share one story."""
    for label, group in (("Merge all", "Merge sub-events"),
                         ("Merge events in selection", "Merge sub-events"),
                         ("Merge with next", "Event Inspector — curation"),
                         ("merge gap", "Detection ▸ Detection")):
        notes = _control(inventory, label, group)["notes"]
        assert "open pore" in notes, f"{label}: no mention of the occupancy refusal"
    assert "the detector's own `merge gap` during a detection run" in manual


# ---------------------------------------------------------------------------------------------
# 4. The detection-tab merge gap changed unit too -- the same trap, one tab over
# ---------------------------------------------------------------------------------------------
def test_docs_give_the_detection_merge_gap_in_milliseconds(manual, inventory, qapp):
    from nanoscope.gui.panels import DetectionPanel

    panel = DetectionPanel()
    try:
        lo, hi = panel.merge_gap_ms.minimum(), panel.merge_gap_ms.maximum()
        suffix = panel.merge_gap_ms.suffix()
    finally:
        panel.deleteLater()
    assert "ms" in suffix and "0 = off" in suffix

    notes = _control(inventory, "merge gap", "Detection ▸ Detection")["notes"]
    assert f"Range {lo:.4f}–{hi:.4f} ms" in notes
    assert "1.0000000 s" not in notes
    assert "in\n**seconds** (15 ms is `0.015`)" not in manual
    assert "**milliseconds** too — 15 ms is `15`" in manual


# ---------------------------------------------------------------------------------------------
# 5. The project format's version, which the architecture note had three behind
# ---------------------------------------------------------------------------------------------
def test_architecture_states_the_project_version_the_app_writes():
    arch = _ARCH.read_text(encoding="utf-8")
    assert f"This build writes `VERSION = {PROJECT_VERSION}`" in arch
    # Every version between the first documented one and the current must be accounted for,
    # or the "each missing key has a defined reading" promise has a hole in it.
    for v in range(2, PROJECT_VERSION + 1):
        assert re.search(rf"\bv{v}\b", arch), f"v{v} is undocumented in ARCHITECTURE.md"
    for key in ("`fits`", "`channel_name` / `channel_kind`", "`CalibrationRec.kind`"):
        assert key in arch, key


