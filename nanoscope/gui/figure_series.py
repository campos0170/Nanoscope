"""Presentation-only adapters for existing pyqtgraph series items.

The registry retains weak item references; geometry, source tables and estimators
are never read or regenerated by a style edit. Native renderers assign semantic
identities with tag_pg_series; fixed-role items have a deterministic fallback.
"""
from dataclasses import replace
import weakref
from PySide6 import QtCore, QtGui
import pyqtgraph as pg
from ..core.figure_series import SeriesDescriptor, stable_series_id
from ..core.figure_style import points_to_logical_pixels, logical_pixels_to_points
from .figure_text import _alive, figure_text_for


class SeriesSelection(QtCore.QObject):
    selected = QtCore.Signal(str)


def _color(item):
    for field in ('symbolBrush', 'brush', 'pen', 'symbolPen'):
        if field.startswith('symbol') and getattr(item, 'opts', {}).get('symbol') is None:
            continue
        value = getattr(item, 'opts', {}).get(field)
        if value is not None:
            try:
                color = pg.mkPen(value).color() if 'Pen' in field or field == 'pen' else pg.mkBrush(value).color()
                if color.isValid(): return color.name()
            except (TypeError, ValueError):
                pass
    return None


def effective_pg_item_style(item):
    """Current scalar ink in physical points, without touching geometry or identity."""
    values = {}
    color = _color(item)
    if color is not None: values['color'] = color
    opts = getattr(item, 'opts', {})
    pen = opts.get('pen', getattr(item, 'pen', None))
    try:
        width = pg.mkPen(pen).widthF() if pen is not None else 0.
        if width > 0: values['line_width_pt'] = logical_pixels_to_points(width)
    except (TypeError, ValueError): pass
    size = opts.get('size') if isinstance(item, pg.ScatterPlotItem) else opts.get('symbolSize') if opts.get('symbol') is not None else None
    if isinstance(size, (float, int)) and size > 0:
        values['marker_size_pt'] = logical_pixels_to_points(size)
    return values


def tag_pg_series(item, *, series_id=None, view='', role='data', identity='',
                  label=None, identity_kind='none', color=None, capabilities=None):
    if item is None or not _alive(item): return None
    if capabilities is None:
        capabilities = ['color', 'visible']
        if callable(getattr(item, 'setPen', None)) or callable(getattr(item, 'setOpts', None)):
            capabilities.append('line_width_pt')
        if (callable(getattr(item, 'setSymbolSize', None)) and getattr(item,'opts',{}).get('symbol') is not None) or isinstance(item, pg.ScatterPlotItem):
            capabilities.append('marker_size_pt')
    descriptor = SeriesDescriptor(series_id or stable_series_id(view, role, identity),
        label or role.capitalize(), role=role, identity_kind=identity_kind,
        identity_key=str(identity) if identity_kind != 'none' else '',
        color=color or _color(item), capabilities=tuple(capabilities))
    item._nanoscope_series_descriptor = descriptor
    return descriptor


def _read(item, name):
    if name == 'visible': return item.isVisible()
    return getattr(item, 'opts', {}).get(name)


def _write(item, name, value):
    if name == 'visible': item.setVisible(value); return
    setter = {'pen':'setPen', 'symbolPen':'setSymbolPen', 'symbolBrush':'setSymbolBrush',
              'fillBrush':'setFillBrush', 'brush':'setBrush', 'symbolSize':'setSymbolSize', 'size':'setSize'}.get(name)
    method = getattr(item, setter, None) if setter else None
    if callable(method): method(value)
    elif callable(getattr(item, 'setOpts', None)): item.setOpts(**{name:value})


def prepare_pg_series_items(items):
    """Remove only our last ink overrides before native/global appearance is applied."""
    for item in items:
        if item is None or not _alive(item): continue
        previous = getattr(item, '_nanoscope_series_applied', {})
        for name, (base, applied) in previous.items():
            try:
                # A fresh renderer may already have installed a new native value.
                if _read(item, name) == applied: _write(item, name, base)
            except (TypeError, ValueError):
                continue
        item._nanoscope_series_applied = {}


def apply_pg_item_style(item, style):
    """Apply validated physical-point overrides, recording only properties we touch."""
    held = {}
    def write(name, value):
        held[name] = (_read(item, name), value)
        _write(item, name, value)
    opts = getattr(item, 'opts', {})
    color = style.get('color')
    width = style.get('line_width_pt')
    for field in ('pen', 'symbolPen'):
        original = opts.get(field)
        if original is None or (not color and width is None): continue
        try:
            pen = pg.mkPen(original)
            if color:
                ink = QtGui.QColor(color); ink.setAlpha(pen.color().alpha()); pen.setColor(ink)
            if width is not None and field == 'pen': pen.setWidthF(points_to_logical_pixels(width))
            write(field, pen)
        except (TypeError, ValueError):
            continue  # Per-point category arrays are handled by their native adapter.
    if color:
        for field in ('symbolBrush', 'fillBrush', 'brush'):
            original = opts.get(field)
            if original is None: continue
            try:
                brush = pg.mkBrush(original); ink = QtGui.QColor(color)
                ink.setAlpha(brush.color().alpha()); brush.setColor(ink); write(field, brush)
            except (TypeError, ValueError):
                continue
    if 'marker_size_pt' in style:
        field = 'size' if isinstance(item, pg.ScatterPlotItem) else 'symbolSize'
        if callable(getattr(item, 'setSize' if field == 'size' else 'setSymbolSize', None)):
            write(field, points_to_logical_pixels(style['marker_size_pt']))
    if 'visible' in style: write('visible', style['visible'])
    item._nanoscope_series_applied = held


def apply_pg_series_styles(plot, state, *, data_items=(), fit_items=(), view=None):
    """Publish stable selectable targets and apply the figure's existing overrides."""
    controller = figure_text_for(plot)
    if view is None:
        view = str(getattr(getattr(controller, 'host', None), 'pin_view', ''))
    emitter = getattr(plot, '_nanoscope_series_selection', None)
    if emitter is None:
        emitter = plot._nanoscope_series_selection = SeriesSelection(plot)
    targets = {}
    for role, items in (('data', data_items), ('fit', fit_items)):
        for index, item in enumerate(items):
            if item is None or not _alive(item): continue
            descriptor = getattr(item, '_nanoscope_series_descriptor', None)
            if descriptor is None:
                descriptor = tag_pg_series(item, view=view, role=role, identity=str(index),
                    label=role.capitalize() + (f' {index + 1}' if len(items) > 1 else ''))
            if descriptor.series_id in targets:
                previous, refs = targets[descriptor.series_id]
                descriptor = replace(previous, capabilities=tuple(dict.fromkeys((*previous.capabilities,*descriptor.capabilities))))
                targets[descriptor.series_id] = descriptor, refs
            targets.setdefault(descriptor.series_id, (descriptor, []))[1].append(weakref.ref(item))
            style = (state.series_styles or {}).get(descriptor.series_id, {})
            apply_pg_item_style(item, style)
            # Fixed native series can opt into item-level selection; no viewport filter.
            if not getattr(item, '_nanoscope_series_selection_wired', False):
                signal = getattr(item, 'sigClicked', None)
                if signal is not None:
                    sink = weakref.ref(emitter); key = descriptor.series_id
                    signal.connect(lambda *_args, sink=sink, key=key: sink().selected.emit(key) if sink() is not None else None)
                    item._nanoscope_series_selection_wired = True
                    clickable = getattr(item, 'setCurveClickable', None)
                    if callable(clickable): clickable(True, width=7)
    plot._nanoscope_series_targets = targets
    return tuple(value[0] for value in targets.values())


def pg_series_descriptors(plots):
    found = {}
    for plot in plots:
        for key, (descriptor, refs) in getattr(plot, '_nanoscope_series_targets', {}).items():
            items = [item for ref in refs if (item := ref()) is not None and _alive(item)]
            if items:
                effective = {}
                for item in items:
                    for field, value in effective_pg_item_style(item).items():effective.setdefault(field, value)
                descriptor = replace(descriptor, extra={**dict(descriptor.extra), 'effective_style':effective})
                found.setdefault(key, descriptor)
    return tuple(found.values())


def sync_series_legend(plot):
    """Link ordinary native legend rows to their actual series visibility."""
    legend=getattr(plot,'legend',None)
    if legend is None:return
    for sample,label in legend.items:
        item=getattr(sample,'item',None)
        if item is None or not hasattr(item,'_nanoscope_series_descriptor'):continue
        visible=item.isVisible()
        sample.setVisible(visible);label.setVisible(visible)
    legend.updateSize()
