"""Local-only release identity and deliberately path-free diagnostic summaries.

No logs, environment variables, recording names, model paths or network access.
The immutable release record is generated by packaging/build_identity.py, never
inferred from today's checkout when an installed app is running.
"""
from __future__ import annotations

from importlib import metadata, resources
import json
import platform
import sys

from ._version import __version__

RUNTIME_DISTRIBUTIONS = ("PySide6", "pyqtgraph", "numpy", "scipy", "pandas", "h5py",
                         "npTDMS", "neo", "scikit-learn", "matplotlib", "seaborn",
                         "pyarrow", "tensorflow", "tensorflow-macos", "keras")


def build_info() -> dict:
    """Return embedded build metadata; a source checkout is honestly unbuilt."""
    try:
        raw = resources.files("nanoscope").joinpath("_build_info.json").read_text(encoding="utf-8")
        data = json.loads(raw)
        if not isinstance(data, dict) or data.get("schema_version") != 1:
            raise ValueError("unsupported metadata")
        return data
    except (OSError, ValueError, TypeError):
        label = "packaged build metadata unavailable" if getattr(sys, "frozen", False) else "unbuilt source checkout"
        return {"schema_version": 1, "version": __version__, "build_id": label,
                "built_at_utc": None, "git_commit": None, "git_dirty": None,
                "source_sha256": None, "bundle_version": None, "environment": {}}


def diagnostic_summary(info: dict | None = None) -> str:
    """Human-readable allowlist, safe to copy voluntarily; nothing is uploaded."""
    record = build_info() if info is None else info
    dirty = record.get("git_dirty")
    rows = [f"NanoScope {record.get('version', __version__)}",
            f"Build: {record.get('build_id') or 'unavailable'}",
            f"Built (UTC): {record.get('built_at_utc') or 'unavailable'}",
            f"Source commit: {record.get('git_commit') or 'unavailable'}",
            "Source working tree: " + ("modified" if dirty is True else "clean" if dirty is False else "unavailable"),
            f"Source SHA-256: {record.get('source_sha256') or 'unavailable'}",
            f"Bundle version: {record.get('bundle_version') or 'unavailable'}",
            f"Runtime: Python {platform.python_version()} · {platform.system()} {platform.release()} · {platform.machine()}",
            f"Execution: {'packaged application' if getattr(sys, 'frozen', False) else 'Python/source'}",
            "", "Runtime dependency versions:"]
    captured = record.get("environment", {}).get("packages", {})
    for name in RUNTIME_DISTRIBUTIONS:
        try:
            version = metadata.version(name)
            origin = "runtime"
        except metadata.PackageNotFoundError:
            version = captured.get(name.lower().replace('_', '-'))
            origin = "build record"
        rows.append(f"  {name}: {version or 'not available'} ({origin})")
    problems = record.get("environment", {}).get("compatibility_issues", [])
    if problems:
        rows.extend(["", "Recorded build-environment compatibility notes:", *[f"  {item}" for item in problems]])
    rows.extend(["", "Local diagnostic summary only. No recording/project names, paths, logs or environment variables are included."])
    return "\n".join(rows)
